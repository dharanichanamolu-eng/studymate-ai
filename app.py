"""StudyMate AI - Streamlit UI. Run: streamlit run app.py"""
import os

import streamlit as st
from dotenv import load_dotenv

load_dotenv()

import study_logic as sl  # noqa: E402
from graph_db import GraphStore  # noqa: E402
from llm_service import llm_configured, model_name, personalize  # noqa: E402

st.set_page_config(page_title="StudyMate AI", page_icon="🧠", layout="wide")

st.markdown("""
<style>
.hero {padding: 1.2rem 1.5rem; border-radius: 14px; margin-bottom: 1rem;
       background: linear-gradient(120deg,#4f46e5,#9333ea); color: white;}
.hero h1 {margin: 0; font-size: 2rem;} .hero p {margin: .3rem 0 0; opacity: .92;}
.pill {display:inline-block; padding:2px 10px; border-radius:999px; font-size:.8rem; margin:2px 4px 2px 0;}
.weak {background:#fee2e2; color:#991b1b;} .good {background:#dcfce7; color:#166534;}
</style>
<div class="hero"><h1>🧠 StudyMate AI</h1>
<p>A study assistant with persistent memory, powered by a FalkorDB knowledge graph.
Tell it what you studied and what was hard, and it remembers and tells you what to revise next.</p></div>
""", unsafe_allow_html=True)


@st.cache_resource(show_spinner=False)
def get_store():
    store = GraphStore()
    store.ping()
    store.ensure_schema()
    return store


# ---- connection check with a friendly failure screen ----
try:
    store = get_store()
    db_ok, db_err = True, ""
except Exception as exc:
    db_ok, db_err = False, str(exc)

if not db_ok:
    st.error("FalkorDB is not reachable, so StudyMate cannot load or save memories.")
    st.code(db_err or "connection failed")
    st.markdown("""**Fix it in 2 steps**
1. Start FalkorDB: `docker run -p 6379:6379 -it --rm falkordb/falkordb:latest`
2. Check `FALKORDB_HOST`, `FALKORDB_PORT` (and username/password for a cloud instance) in your `.env`, then reload.""")
    if st.button("Retry connection"):
        get_store.clear()
        st.rerun()
    st.stop()

# ---- sidebar ----
with st.sidebar:
    st.header("Student")
    mode = st.radio("Mode", ["My study memory", "Demo student (sample data)"],
                    help="Demo mode uses a separate student ID so sample data never mixes with real data.")
    if mode.startswith("Demo"):
        sid = "demo-student"
        st.info("Demo mode: sample data goes to student `demo-student` only.")
        c1, c2 = st.columns(2)
        if c1.button("Load sample"):
            store.clear_student(sid)
            for rep in sl.DEMO_REPORTS:
                store.save_session(sid, sl.parse_study_input(rep), rep)
            st.rerun()
        if c2.button("Clear demo"):
            store.clear_student(sid)
            st.rerun()
    else:
        sid = st.text_input("Student ID", os.getenv("STUDENT_ID", "student-1")).strip() or "student-1"

    st.divider()
    st.markdown("**Status**")
    st.success("FalkorDB: connected")
    if llm_configured():
        st.success(f"LLM: configured ({model_name()})")
    else:
        st.warning("LLM: not configured, using rule-based fallback")

    weak = store.weak_topics(sid)
    understood = store.understood_topics(sid)
    st.divider()
    st.markdown("**⚠️ Weak areas**")
    if weak:
        for w in weak:
            st.markdown(f"<span class='pill weak'>{w['topic']} · {w['subject']} · {w['difficulty']}/5</span>",
                        unsafe_allow_html=True)
    else:
        st.caption("None recorded yet.")
    st.markdown("**✅ Understood topics**")
    if understood:
        for u in understood:
            st.markdown(f"<span class='pill good'>{u['topic']} · {u['subject']}</span>", unsafe_allow_html=True)
    else:
        st.caption("None recorded yet.")
    st.caption(f"Sessions stored: {store.session_count(sid)}")

# ---- state ----
if "messages" not in st.session_state:
    st.session_state.messages = {}
msgs = st.session_state.messages.setdefault(sid, [
    {"role": "assistant", "content": "Hi! Tell me what you studied and what was difficult, e.g. "
     "*“I studied Python loops today. I understand for loops, but nested loops are difficult for me.”* "
     "Later, ask **What should I study next?**", "source": None}])
if "latest_rec" not in st.session_state:
    st.session_state.latest_rec = {}

left, right = st.columns([3, 2], gap="large")

with right:
    st.subheader("📌 Latest recommended tasks")
    rec_state = st.session_state.latest_rec.get(sid)
    if rec_state:
        st.markdown(rec_state["text"])
        st.caption(f"Generated by: {rec_state['source']}")
    else:
        st.caption("Ask “What should I study next?” to get a recommendation based on your graph memory.")

    st.subheader("🕸️ Memory graph")
    edges = store.graph_edges(sid)
    if edges:
        lines = ["digraph G { rankdir=LR; bgcolor=transparent; node [style=filled, fontname=Helvetica];",
                 f'"{sid}" [shape=ellipse, fillcolor="#c7d2fe"];']
        for subj in sorted({e["subject"] for e in edges}):
            lines.append(f'"{sid}" -> "{subj}" [label="STUDIES"]; "{subj}" [shape=box, fillcolor="#e9d5ff"];')
        for e in edges:
            color = "#fecaca" if e["struggling"] else ("#bbf7d0" if e["understood"] else "#e5e7eb")
            lines.append(f'"{e["subject"]}" -> "{e["topic"]}" [label="CONTAINS"]; '
                         f'"{e["topic"]}" [fillcolor="{color}"];')
            if e["struggling"]:
                lines.append(f'"{sid}" -> "{e["topic"]}" [label="STRUGGLES_WITH", color="red", fontcolor="red"];')
        lines.append("}")
        st.graphviz_chart("\n".join(lines))
        st.caption("Red = struggling, green = understood, grey = studied only.")
    else:
        st.caption("Your graph is empty. Record a study session first.")

    with st.expander("Recent sessions (from FalkorDB)"):
        for r in store.recent_sessions(sid, 10):
            st.write(f"{r['date'][:16].replace('T', ' ')} · {r['subject']} · **{r['topic']}** ({r['outcome']})")

with left:
    for m in msgs:
        with st.chat_message(m["role"]):
            st.markdown(m["content"])
            if m.get("source"):
                st.caption(f"Generated by: {m['source']}")

    prompt = st.chat_input("What did you study today? Or ask: What should I study next?")
    if prompt:
        msgs.append({"role": "user", "content": prompt, "source": None})
        intent = sl.detect_intent(prompt)
        if intent == "recommend":
            weak = store.weak_topics(sid)
            recent = store.recent_sessions(sid, 20)
            if not weak and not recent:
                reply, src = ("I have no study history for this student ID yet, so I won't guess. "
                              "Record a session first (e.g. *I studied Python loops today…*), or switch to "
                              "**Demo student** in the sidebar for clearly labelled sample data.",
                              "System message (no LLM used)")
            else:
                related = {w["topic"]: store.related_understood(sid, w["subject"], w["topic"]) for w in weak[:1]}
                rec = sl.build_recommendation(weak, store.understood_topics(sid), recent, related)
                reply, src = personalize(rec, weak, recent)
                st.session_state.latest_rec[sid] = {"text": reply, "source": src}
        elif intent == "memory":
            recent = store.recent_sessions(sid, 10)
            if recent:
                reply = "Here is what I retrieved from FalkorDB:\n\n" + "\n".join(
                    f"- {r['date'][:10]} · {r['subject']} · **{r['topic']}** ({r['outcome']})" for r in recent)
            else:
                reply = "Nothing stored for this student ID yet."
            src = "FalkorDB query (no LLM used)"
        else:
            parsed = sl.parse_study_input(prompt)
            if not parsed:
                reply = ("I couldn't find a study report in that. Try: *I studied Python loops today. "
                         "I understand for loops, but nested loops are difficult for me.*")
            else:
                store.save_session(sid, parsed, prompt)
                reply = ("✅ Saved to FalkorDB.  \n" + sl.summarize_parsed(parsed) +
                         "\n\nAsk **What should I study next?** for a recommendation.")
            src = "Rule-based extraction (no LLM used)"
        msgs.append({"role": "assistant", "content": reply, "source": src})
        st.rerun()
